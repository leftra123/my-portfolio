import type { Metadata } from "next";
import { AutoGenerated, Generator } from "@/components/admin/generator";
import { PageHeader } from "@/components/admin/page-header";
import { readCollection } from "@/lib/admin/store";
import { aiAvailable } from "@/lib/generator/draft";
import { screenshotAvailable } from "@/lib/generator/screenshot";

export const metadata: Metadata = { title: "Generador" };

export default async function GeneratorPage() {
  const projects = (await readCollection("proyectos")).map(({ slug, name }) => ({ slug, name }));
  const local = !process.env.VERCEL;

  return (
    <>
      <PageHeader
        eyebrow="Generador"
        title="Genera, no redactes"
        description="Apunta a un repositorio y obtén la ficha del proyecto con sus cifras reales; toma capturas de sitios y redacta posts. Todo queda como borrador hasta que lo revises."
      />
      <Generator
        aiReady={aiAvailable()}
        screenshotReady={await screenshotAvailable()}
        projects={projects}
        examples={[
          "leftra123/teleprompter",
          "leftra123/hydroflow-monitor",
          ...(local ? ["~/Documents/01-Proyectos-Dev/personal/inventario-casa"] : []),
        ]}
      />
      <AutoGenerated projects={projects} />
    </>
  );
}
